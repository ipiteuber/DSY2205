-- =====================================================
-- ms-usuarios
-- =====================================================

CREATE TABLE ROLES (
    ID_ROL      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE      VARCHAR2(30)  NOT NULL,
    DESCRIPCION VARCHAR2(200),
    CONSTRAINT PK_ROLES PRIMARY KEY (ID_ROL),
    CONSTRAINT UQ_ROLES_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIOS (
    ID_USUARIO      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE_USUARIO  VARCHAR2(30)  NOT NULL,
    EMAIL           VARCHAR2(100) NOT NULL,
    PASSWORD_HASH   VARCHAR2(100) NOT NULL,
    NOMBRE_COMPLETO VARCHAR2(100) NOT NULL,
    ID_ROL          NUMBER        NOT NULL,
    ACTIVO          NUMBER(1)     DEFAULT 1 NOT NULL,
    FECHA_REGISTRO  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIOS_NOMBRE UNIQUE (NOMBRE_USUARIO),
    CONSTRAINT UQ_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_USUARIOS_ROL FOREIGN KEY (ID_ROL) REFERENCES ROLES (ID_ROL),
    CONSTRAINT CK_USUARIOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);

-- =====================================================
-- ms-foro
-- ID_USUARIO no tiene FK porque los usuarios pertenecen a ms-usuarios
-- =====================================================

CREATE TABLE CATEGORIAS (
    ID_CATEGORIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE       VARCHAR2(50) NOT NULL,
    DESCRIPCION  VARCHAR2(200),
    CONSTRAINT PK_CATEGORIAS PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UQ_CATEGORIAS_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE TEMAS (
    ID_TEMA        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITULO         VARCHAR2(150)  NOT NULL,
    CONTENIDO      VARCHAR2(4000) NOT NULL,
    ID_CATEGORIA   NUMBER         NOT NULL,
    ID_USUARIO     NUMBER         NOT NULL,
    FECHA_CREACION TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO         VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL,
    VISITAS        NUMBER         DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TEMAS PRIMARY KEY (ID_TEMA),
    CONSTRAINT FK_TEMAS_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIAS (ID_CATEGORIA),
    CONSTRAINT CK_TEMAS_ESTADO CHECK (ESTADO IN ('ACTIVO', 'BANEADO'))
);

CREATE TABLE COMENTARIOS (
    ID_COMENTARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_TEMA       NUMBER         NOT NULL,
    ID_USUARIO    NUMBER         NOT NULL,
    CONTENIDO     VARCHAR2(1000) NOT NULL,
    FECHA         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO        VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_COMENTARIOS PRIMARY KEY (ID_COMENTARIO),
    CONSTRAINT FK_COMENTARIOS_TEMA FOREIGN KEY (ID_TEMA) REFERENCES TEMAS (ID_TEMA) ON DELETE CASCADE,
    CONSTRAINT CK_COMENTARIOS_ESTADO CHECK (ESTADO IN ('ACTIVO', 'BANEADO'))
);

CREATE INDEX IX_TEMAS_CATEGORIA ON TEMAS (ID_CATEGORIA);
CREATE INDEX IX_COMENTARIOS_TEMA ON COMENTARIOS (ID_TEMA);

-- =====================================================
-- ms-moderacion
-- ID_CONTENIDO apunta a TEMAS o COMENTARIOS segun TIPO_CONTENIDO
-- =====================================================

CREATE TABLE NORMAS (
    ID_NORMA    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITULO      VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(500) NOT NULL,
    CONSTRAINT PK_NORMAS PRIMARY KEY (ID_NORMA)
);

CREATE TABLE MODERACIONES (
    ID_MODERACION  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TIPO_CONTENIDO VARCHAR2(15)  NOT NULL,
    ID_CONTENIDO   NUMBER        NOT NULL,
    ID_MODERADOR   NUMBER        NOT NULL,
    ACCION         VARCHAR2(15)  NOT NULL,
    ID_NORMA       NUMBER,
    MOTIVO         VARCHAR2(500) NOT NULL,
    FECHA          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MODERACIONES PRIMARY KEY (ID_MODERACION),
    CONSTRAINT FK_MODERACIONES_NORMA FOREIGN KEY (ID_NORMA) REFERENCES NORMAS (ID_NORMA),
    CONSTRAINT CK_MODERACIONES_TIPO CHECK (TIPO_CONTENIDO IN ('TEMA', 'COMENTARIO')),
    CONSTRAINT CK_MODERACIONES_ACCION CHECK (ACCION IN ('BANEAR', 'RESTAURAR'))
);

