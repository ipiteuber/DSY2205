-- Los tres microservicios usan el mismo usuario FORO, pero cada uno trabaja solo con sus tablas

   SET DEFINE OFF;

begin
   execute immediate 'DROP USER FORO CASCADE';
exception
   when others then
      if sqlcode != -1918 then
         raise;
      end if;
end;
